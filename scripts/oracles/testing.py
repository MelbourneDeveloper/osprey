"""CPython oracle for @osprey/testing: numpy.isclose verdicts.

Writes packages/testing/tests/expected.py, the Python-flavor constants module the
suite compares `Check.near` against ([PORT-TEST-ORACLE], spec 0043). Run with the
oracle virtualenv: `python -I scripts/oracles/testing.py`.
"""
import pathlib
import platform

import numpy

RTOL, ATOL = 1e-05, 1e-08
PAIRS = [
    (1.0 + 1e-06, 1.0), (1.001, 1.0), (0.0, 1e-09), (0.0, 1e-07), (-1.0, -1.0000001),
    (1e300, 1.0000001e300), (1e300, 1.0001e300), (5e-324, 0.0), (-0.0, 0.0), (100.0, 100.001),
    (100.0, 100.002), (1e-08, 2e-08), (-3.5, 3.5), (2.0, 1.99998), (2.0, 1.99997),
]
SPECIAL = [("inf", "inf"), ("inf", "-inf"), ("nan", "nan"), ("nan", "1.0"), ("-inf", "-inf"), ("inf", "1e308")]


def verdicts(pairs):
    return [bool(numpy.isclose(float(a), float(b), rtol=RTOL, atol=ATOL, equal_nan=True)) for a, b in pairs]


def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    lines = [
        "# osprey: flavor=python",
        "# osprey: namespace=testing_expected",
        "# osprey: module=Expected",
        f'"""numpy.isclose(a, b, rtol={RTOL}, atol={ATOL}, equal_nan=True) verdicts.',
        "",
        f"Generated by scripts/oracles/testing.py with CPython {platform.python_version()} and numpy {numpy.__version__}.",
        'Do not edit: rerun the oracle."""',
        "",
        '__all__ = ["PAIRS", "VERDICTS", "SPECIAL", "SPECIAL_VERDICTS"]',
        "",
        f"PAIRS = {[[a, b] for a, b in PAIRS]!r}",
        f"VERDICTS = {verdicts(PAIRS)!r}",
        f"SPECIAL = {[[a, b] for a, b in SPECIAL]!r}",
        f"SPECIAL_VERDICTS = {verdicts(SPECIAL)!r}",
        "",
    ]
    text = "\n".join(lines).replace("True", "True").replace("'", '"')
    (root / "packages/testing/tests/expected.py").write_text(text)


if __name__ == "__main__":
    main()
